package com.miniproject.aismartexpense

import android.content.Intent
import android.service.notification.NotificationListenerService
import android.service.notification.StatusBarNotification
import android.util.Log

class NotificationReaderService : NotificationListenerService() {

    companion object {

        private const val TAG = "ExpenseNotification"

        /*
         * Checks whether the notification is actually
         * related to an outgoing payment/expense.
         */
        private fun isPaymentNotification(
            text: String
        ): Boolean {

            val lowerText = text.lowercase()

            // Must contain a money amount
            val amountRegex = Regex(
                """(?i)(₹|rs\.?|inr)\s*[\d,]+(?:\.\d{1,2})?"""
            )

            val hasAmount =
                amountRegex.containsMatchIn(text)

            if (!hasAmount) {
                return false
            }

            /*
             * Words commonly found in outgoing
             * payment notifications.
             */
            val paymentKeywords = listOf(

                "paid",
                "payment",
                "payment successful",
                "payment completed",
                "debited",
                "debit",
                "sent",
                "transferred",
                "transfer successful",
                "upi",
                "transaction"
            )

            val hasPaymentKeyword =
                paymentKeywords.any {
                    lowerText.contains(it)
                }

            if (!hasPaymentKeyword) {
                return false
            }

            /*
             * Ignore notifications that are usually
             * NOT expenses.
             */
            val ignoredKeywords = listOf(

                "received",
                "credited",
                "credit alert",
                "cashback",
                "refund",
                "refunded",
                "offer",
                "offers",
                "discount",
                "coupon",
                "reward",
                "reminder",
                "due soon",
                "pay your bill"
            )

            val shouldIgnore =
                ignoredKeywords.any {
                    lowerText.contains(it)
                }

            if (shouldIgnore) {
                return false
            }

            return true
        }
    }

    override fun onListenerConnected() {

        super.onListenerConnected()

        Log.d(
            TAG,
            "NOTIFICATION LISTENER CONNECTED"
        )
    }

    override fun onListenerDisconnected() {

        super.onListenerDisconnected()

        Log.d(
            TAG,
            "NOTIFICATION LISTENER DISCONNECTED"
        )
    }

    override fun onNotificationPosted(
        sbn: StatusBarNotification
    ) {

        /*
         * Ignore notifications generated by
         * our own application.
         */
        if (sbn.packageName == packageName) {
            return
        }

        val extras =
            sbn.notification.extras

        val title =
            extras
                .getCharSequence("android.title")
                ?.toString()
                ?: ""

        val text =
            extras
                .getCharSequence("android.text")
                ?.toString()
                ?: ""

        val bigText =
            extras
                .getCharSequence("android.bigText")
                ?.toString()
                ?: ""

        val subText =
            extras
                .getCharSequence("android.subText")
                ?.toString()
                ?: ""

        /*
         * Combine all notification fields.
         */
        val combinedText =
            """
            $title
            $text
            $bigText
            $subText
            """.trimIndent()

        Log.d(
            TAG,
            "NEW NOTIFICATION FROM: ${sbn.packageName}"
        )

        Log.d(
            TAG,
            "TEXT: $combinedText"
        )

        /*
         * IMPORTANT:
         * Ignore everything that isn't a payment.
         */
        if (!isPaymentNotification(combinedText)) {

            Log.d(
                TAG,
                "IGNORED - NOT A PAYMENT"
            )

            return
        }

        Log.d(
            TAG,
            "PAYMENT NOTIFICATION DETECTED"
        )

        /*
         * Extract merchant and amount.
         */
        val parsed =
            TransactionParser.parse(
                combinedText
            )

        if (parsed == null) {

            Log.d(
                TAG,
                "PAYMENT DETECTED BUT COULD NOT EXTRACT DETAILS"
            )

            return
        }

        Log.d(
            TAG,
            "========== PAYMENT =========="
        )

        Log.d(
            TAG,
            "MERCHANT: ${parsed.merchant}"
        )

        Log.d(
            TAG,
            "AMOUNT: ₹${parsed.amount}"
        )

        /*
         * Open database.
         */
        val databaseHelper =
            DatabaseHelper(
                applicationContext
            )

        /*
         * Automatically categorize.
         */
        val category =
            NaiveBayesClassifier.classify(
                parsed.merchant
            )

        Log.d(
            TAG,
            "CATEGORY: $category"
        )

        /*
         * Check for duplicate transaction.
         *
         * This prevents GPay + SMS from creating
         * the same expense twice.
         */
        val isDuplicate =
            databaseHelper.isDuplicateRecentExpense(
                merchant = parsed.merchant,
                amount = parsed.amount
            )

        if (isDuplicate) {

            Log.d(
                TAG,
                "DUPLICATE PAYMENT - IGNORED"
            )

            return
        }

        /*
         * Save the payment.
         */
        databaseHelper.addExpense(

            merchant =
                parsed.merchant,

            amount =
                parsed.amount,

            category =
                category
        )

        Log.d(
            TAG,
            "PAYMENT SAVED TO DATABASE"
        )

        /*
         * Tell MainActivity to refresh
         * the transaction history.
         */
        val updateIntent =
            Intent(
                "com.miniproject.aismartexpense.NEW_TRANSACTION"
            )

        updateIntent.setPackage(
            applicationContext.packageName
        )

        applicationContext.sendBroadcast(
            updateIntent
        )

        Log.d(
            TAG,
            "UI UPDATE SIGNAL SENT"
        )

        Log.d(
            TAG,
            "============================="
        )
    }
}